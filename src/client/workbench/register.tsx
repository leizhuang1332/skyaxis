/** The detail tab seat id/order (D5 naming, unchanged from P1a). */
export const WORKBENCH_SEAT_ID = 'aiWorkbench'
export const WORKBENCH_SEAT_ORDER = 40

/** The minimal face of ctx.sessions the strip and picker consume. */
export type SessionsFace = WorkbenchSessionsFace

/** Narrow ctx.sessions into the minimal face (see the file header note). */
function sessionsFace(ctx: Context): SessionsFace | undefined {
  const sessions = (ctx as unknown as { sessions?: { list: unknown; subagentAddress: (id: string) => unknown; open: (id: string) => void; openSubagent: (address: never) => void } }).sessions
  if (sessions === undefined || sessions.list === undefined) return undefined
  const list = sessions.list as {
    getSnapshot(): { ids: readonly string[]; byId: Readonly<Record<string, { id: string; displayTitle: string; running: boolean; blank: boolean } | undefined>> }
    subscribe(listener: () => void): () => void
  }
  return {
    get ids() { return list.getSnapshot().ids },
    get summariesById() { return list.getSnapshot().byId },
    subscribe: (listener) => list.subscribe(listener),
    navigate(sessionId: string): void {
      const address = sessions.subagentAddress(sessionId)
      if (address !== undefined) {
        sessions.openSubagent(address as never)
        return
      }
      if (list.getSnapshot().ids.includes(sessionId)) sessions.open(sessionId)
    },
  }
}

export function registerWorkbenchView(ctx: Context, waiting?: WaitingFace): () => void {
  registerWorkbenchDictionaries(ctx)
  const t = ctx.locale.bind(WORKBENCH_LOCALE_NS)

  const fetcher = createWorkbenchFetcher()
  const store = createWorkbenchStore()
  const controller = createWorkbenchController(store, fetcher)
  const sessions = sessionsFace(ctx)
  // P5a delivery face — undefined in jsdom / conversation-less compositions
  // (honest degrade: the SOW modal then hides its delivery button).
  const deliver = createSowDelivery(ctx)
  const seat = createWorkbenchTabSeat({ t: t satisfies WorkbenchT, store, controller, sessions, waiting, deliver })

  const disposeSeat = ctx.slots.inject('requirements.detail.view', () =>
    ctx.slots.register(
      { name: 'requirements.detail.view', id: WORKBENCH_SEAT_ID, order: WORKBENCH_SEAT_ORDER, label: () => t('detail.tab.aiWorkbench') },
      seat,
    ))

  return () => {
    disposeSeat()
    controller.dispose()
  }
}

/** Test/export helper: subscribe a component to the live session list. */
export function useSessionSummaries(sessions: SessionsFace | undefined): { ids: readonly string[]; byId: WorkbenchSessionsFace['summariesById'] } {
  const snapshot = useSyncExternalStore(
    (listener) => (sessions !== undefined ? sessions.subscribe(listener) : () => {}),
    () => (sessions !== undefined ? sessions : { ids: [] as readonly string[], summariesById: {} }),
  )
  return { ids: snapshot.ids, byId: snapshot.summariesById }
}

